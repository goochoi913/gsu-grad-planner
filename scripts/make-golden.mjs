/**
 * Records what the ORIGINAL planner did, so the TypeScript port can be held to it.
 *
 * Loads js/data.js and js/planner.js exactly as they were last committed (classic
 * browser scripts sharing globals) into one Node vm context, runs the synthetic
 * scenario battery in scripts/fixtures/scenarios.mjs against them, and writes
 * scripts/fixtures/golden.json. scripts/logic-test.ts (npm test) replays the same
 * battery through src/lib/planner.ts and compares.
 *
 *   node scripts/make-golden.mjs              # from the pinned commit below
 *   GOLDEN_REV=<commit> node scripts/make-golden.mjs
 *
 * Only regenerate when the ORIGINAL behaviour is what you want to capture; a change in
 * the port is checked against this file, not recorded into it.
 */
import { createHash } from 'node:crypto'
import { execFileSync } from 'node:child_process'
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import vm from 'node:vm'
import { API_NAMES, scenarios, ser } from './fixtures/scenarios.mjs'

// The last commit with the original vanilla-JS app (js/data.js + js/planner.js).
const REV = process.env.GOLDEN_REV || 'f456ea6c9b72ef4a941b8ff443e33fe11b596255'
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const out = path.join(root, 'scripts/fixtures/golden.json')

const show = (file) => execFileSync('git', ['show', `${REV}:${file}`], { cwd: root, encoding: 'utf8', maxBuffer: 1 << 26 })
const sources = { 'js/data.js': show('js/data.js'), 'js/planner.js': show('js/planner.js') }

const ctx = vm.createContext({})
for (const [file, code] of Object.entries(sources)) vm.runInContext(code, ctx, { filename: file })
const api = vm.runInContext(`({ ${API_NAMES.join(', ')} })`, ctx)

const results = []
for (const [name, fn] of scenarios(api)) {
  let output
  try {
    output = ser(fn())
  } catch (e) {
    output = { __throws: String(e?.message ?? e) }
  }
  results.push({ name, output })
}

const names = new Set()
for (const r of results) {
  if (names.has(r.name)) throw new Error(`duplicate scenario name: ${r.name}`)
  names.add(r.name)
}

const sha = (s) => createHash('sha256').update(s).digest('hex').slice(0, 16)
const meta = {
  note: 'Generated by scripts/make-golden.mjs from the original js/planner.js + js/data.js. Synthetic data only.',
  rev: REV,
  sha256: Object.fromEntries(Object.entries(sources).map(([f, s]) => [f, sha(s)])),
  scenarios: results.length,
}
// One scenario per line keeps diffs readable.
const body = results.map((r) => JSON.stringify(r)).join(',\n')
fs.mkdirSync(path.dirname(out), { recursive: true })
fs.writeFileSync(out, `{"meta":${JSON.stringify(meta)},\n"scenarios":[\n${body}\n]}\n`)
const throws = results.filter((r) => r.output && r.output.__throws)
console.log(`golden: ${results.length} scenarios from ${REV.slice(0, 7)} → ${path.relative(root, out)} (${(fs.statSync(out).size / 1024).toFixed(0)} KB)${throws.length ? ` · ${throws.length} record a thrown error: ${throws.map((t) => t.name).join(', ')}` : ''}`)
